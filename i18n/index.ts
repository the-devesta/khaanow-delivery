export async function loadSavedLanguage() {
  const saved = await AsyncStorage.getItem(LANGUAGE_KEY);
  if (saved && LANGUAGES.some((language) => language.code === saved)) {
    await i18n.changeLanguage(saved);
  }
  return i18n.language as AppLanguage;
}

export async function setSavedLanguage(language: AppLanguage) {
  await AsyncStorage.setItem(LANGUAGE_KEY, language);
  await i18n.changeLanguage(language);
}

export function getLanguageLabel(language = i18n.language) {
  return (
    LANGUAGES.find((item) => item.code === language)?.nativeLabel ||
    LANGUAGES[0].nativeLabel
  );
}

